
def str_xor(secret, key):
    new_key = key
    i = 0

    while len(new_key) < len(secret):
        new_key += key[i]
        i = (i + 1) % len(key)

    return "".join(
        chr(ord(s) ^ ord(k))
        for s, k in zip(secret, new_key)
    )


flag_enc = bytes([
    0x04, 0x0d, 0x0a, 0x0d, 0x01, 0x18, 0x1c,
    0x15, 0x58, 0x18, 0x11, 0x41, 0x09, 0x5f,
    0x1f, 0x10, 0x3b, 0x1b, 0x55, 0x1a, 0x34,
    0x5d, 0x51, 0x40, 0x54, 0x09, 0x05, 0x04,
    0x57, 0x1b, 0x11, 0x31, 0x5c, 0x0d, 0x06,
    0x11, 0x5d, 0x5b, 0x5e, 0x0f, 0x19
]).decode("latin-1")

flag = str_xor(flag_enc, "enkidu")

if flag == "":
    print("String XOR encountered a problem, quitting.")
else:
    print("That is correct! Here's your flag: " + flag)
